/** Flattened, with the coarse group derived so it can never disagree. */
export const EXERCISE_CATALOG: CatalogEntry[] = Object.entries(BY_TARGET).flatMap(
  ([target, rows]) =>
    (rows ?? []).map(([name, equipment, kind]) => ({
      name,
      muscle: GROUP_OF[target as MuscleTarget],
      target: target as MuscleTarget,
      equipment,
      kind: kind ?? ('weight_reps' as ExerciseKind),
    })),
);
