import type { Equipment, ExerciseKind, MuscleGroup, MuscleTarget } from '@atlas/shared';

/**
 * The shared catalog, seeded once with `userId = null` so every account gets it.
 *
 * It used to be forty-eight movements, chosen to keep the picker scannable. That
 * was the wrong trade: a catalog you cannot find your exercise in is not a
 * scannable catalog, it is a dead end with an "add exercise" button, and the
 * thing that made it obvious was hip abduction — a machine in every commercial
 * gym, filed under "legs" along with squats, and therefore unfindable.
 *
 * So it is now broad, and the picker does the narrowing instead: search by name,
 * filter by the specific muscle, filter by what the equipment is. Breadth costs
 * nothing once the list is filterable, and the entries carry enough structure
 * for the filters to be honest.
 *
 * ENTRIES ARE KEYED BY TARGET, not listed flat, so the muscle a movement trains
 * is stated once for a whole block and the coarse group is DERIVED from it.
 * Writing both by hand on four hundred rows guarantees a few disagree with each
 * other, and a "back" exercise filed under quads is worse than a missing one.
 */
export interface CatalogEntry {
  name: string;
  muscle: MuscleGroup;
  target: MuscleTarget;
  equipment: Equipment;
  kind: ExerciseKind;
}

